def related(slug, n=8):
    i = _INDEX[slug]
    it = ITEMS[i]
    c = Ctx(it)
    out = []

    def take(lst, k):
        if not lst:
            return
        pos = lst.index(i) if i in lst else _h(slug) % len(lst)
        for step in range(1, len(lst)):
            if k <= 0 or len(out) >= n:
                return
            cand = lst[(pos + step) % len(lst)]
            if cand != i and cand not in out:
                out.append(cand)
                k -= 1

    take(_BY_TOPIC[it["topic"]], 4)
    if it["aud"]:
        take(_BY_AUD[it["aud"]], 4)
    else:
        take(_BY_SFX[c.sfx], 4)
    take(_BY_TOPIC[it["topic"]], n - len(out))
    return [ITEMS[k] for k in out[:n]]


@lru_cache(maxsize=4096)
def compose(slug):
    it = BY_SLUG.get(slug)
    if not it:
        return None
    c = Ctx(it)
    order = list(SECTIONS[c.g])
    mid = order[1:-1]
    r = _h(slug + "::order") % len(mid)
    order = [order[0]] + mid[r:] + mid[:r] + [order[-1]]
    if c.aud:
        order.insert(1, "aud")
    else:
        order.append("summary")
    sections = []
    for key in order:
        h2, paras, items = SEC_FN[key](c)
        sections.append({"key": key, "h2": h2, "paras": paras, "bullets": items,
                         "ordered": key == "process"})
    ans = answer(c)
    title = f"{c.kw} — {c.p(TITLE_TAIL[c.g], 'title')}"
    desc = ans if len(ans) <= 150 else ans[:148].rsplit(" ", 1)[0] + "…"
    return {"item": it, "kw": c.kw, "topic": c.T, "aud": c.A, "group": c.g, "title": title,
            "description": desc, "answer": ans, "intro2": intro2(c), "sections": sections, "faqs": faqs(c),
            "related": related(slug)}


