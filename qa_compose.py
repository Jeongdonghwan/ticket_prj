def _jong(word):
    """받침 코드: 0 없음, 8 ㄹ, 그 외 있음. 영문·숫자는 발음 근사."""
    c = word.strip()[-1]
    if "가" <= c <= "힣":
        return (ord(c) - 0xAC00) % 28
    if c in "0136789":
        return 8 if c in "178" else 1
    if c.lower() in "lmn":
        return 1
    return 0


_PAIRS = {"은": ("은", "는"), "이": ("이", "가"), "을": ("을", "를"), "과": ("과", "와"),
          "으로": ("으로", "로"), "이라": ("이라", "라"), "이나": ("이나", "나")}


def j(word, p):
    r = _jong(word)
    if p == "으로" and r == 8:
        return word + "로"
    a, b = _PAIRS[p]
    return word + (a if r else b)


def _h(seed):
    return int(hashlib.md5(seed.encode("utf-8")).hexdigest(), 16)


def pick(seq, seed):
    return seq[_h(seed) % len(seq)]


