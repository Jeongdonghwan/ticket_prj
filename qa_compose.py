def match(text, n=4):
    """블로그 글 제목·요약과 겹치는 Q&A n개 (주제 3점, 대상자 2점, 질문 유형 1점). 없으면 주제 대표 페이지."""
    text = text or ""
    scored = []
    for i, it in enumerate(ITEMS):
        c = Ctx(it)
        sc = (3 if c.T in text or (len(c.T) > 3 and c.T.replace("대출", "") in text) else 0) \
            + (2 if c.A and c.A in text else 0) + (1 if c.sfx and c.sfx in text else 0)
        if sc:
            scored.append((-sc, i))
    picks = [ITEMS[i] for _, i in sorted(scored)[:n]]
    return picks or [ITEMS[idxs[0]] for idxs in list(_BY_TOPIC.values())[:n]]


def text_of(page):
    parts = [page["answer"], page["intro2"]]
    for s in page["sections"]:
        parts += [s["h2"]] + s["paras"] + s["bullets"]
    for q, a in page["faqs"]:
        parts += [q, a]
    return "\n".join(parts)


